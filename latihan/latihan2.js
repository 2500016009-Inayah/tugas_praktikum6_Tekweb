// Latihan 2: Operator dan Fungsi

function hitungLuas(panjang, lebar) {
  return panjang * lebar;
}

// Perhitungan pertama
let luas1 = hitungLuas(5, 8);
console.log("Luas persegi panjang:");
console.log("Panjang 5 dan lebar 8 = " + luas1);

// Perhitungan kedua
let luas2 = hitungLuas(10, 3);
console.log("Panjang 10 dan lebar 3 = " + luas2);

// Perhitungan ketiga
let luas3 = hitungLuas(7, 4);
console.log("Panjang 7 dan lebar 4 = " + luas3);
